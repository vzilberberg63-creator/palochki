/** Монеты и награды. Числа собраны здесь, чтобы балансировать в одном месте. */

/** Сколько секунд добавляет реклама, когда время вышло. Один раз за попытку. */
export const CONTINUE_SECONDS = 30;

/** Монеты за рекламу в магазине — для тех, кому чуть-чуть не хватает на стиль. */
export const SHOP_AD_COINS = 25;

/** Во сколько раз реклама на экране победы умножает монеты. */
export const AD_COIN_MULTIPLIER = 2;

/**
 * Монеты за пройденный уровень: основа, за каждую звезду и за очки.
 * Пример: уровень 1 на 3 звезды ≈ 20 монет, уровень 6 с хорошим комбо ≈ 35.
 * Первый платный стиль (120) — примерно 5 уровней, самый дорогой (2000) — долгая цель.
 */
export function coinsForWin(stars: number, score: number): number {
  if (stars <= 0) return 0;
  return 5 + 5 * stars + Math.floor(score / 100);
}
